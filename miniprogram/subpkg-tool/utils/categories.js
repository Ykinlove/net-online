/**
 * 把一条条目归到唯一一个分类。
 *
 * 做法：给每个分类算加权命中分——关键词出现在 name 里算 3 分，
 * 出现在 kw 里算 1 分。取最高分的分类；同分时按 CATEGORIES 的顺序取靠前的
 * （顺序即优先级）。
 *
 * 一条都不中的落到第一个分类兜底（「基础操作」）——
 * 宁可归得不够精确，也不能让条目在目录里消失。
 * 兜底必须放在**第一个**：放在最后的话，所有没命中的条目
 * 都会堆到最后一个分类（「项目与职业」），那类会瞬间膨胀到几百条，
 * 而其他类全是空的。
 */
function classifyItem(item, categories) {
  const cats = categories || CATEGORIES;
  const name = String(item.name || '').toLowerCase();
  const kwText = (item.kw || []).join(' ').toLowerCase();

  let bestIdx = -1;
  let bestScore = 0;
  for (let c = 0; c < cats.length; c++) {
    const cat = cats[c];
    let score = 0;
    for (let k = 0; k < cat.kw.length; k++) {
      const w = cat.kw[k];
      if (name.indexOf(w) >= 0) score += 3;
      else if (kwText.indexOf(w) >= 0) score += 1;
    }
    if (score > bestScore) {
      bestScore = score;
      bestIdx = c;
    }
  }
  if (bestIdx < 0) return { key: cats[0].key, score: 0 };
  return { key: cats[bestIdx].key, score: bestScore };
}

module.exports = { CATEGORIES, classifyItem };
