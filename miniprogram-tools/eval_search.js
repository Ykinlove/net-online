/* 逐条输出模式：`node eval_search.js all > now.txt`，改排序前后 diff 这两份，
   就能看出是修好了哪几条、又弄坏了哪几条。别在外面另写脚本复刻判定——
   判定逻辑一旦抄一份，diff 出来的差异就是抄错而不是改坏了。 */
const dumpAll = process.argv[2] === 'all';

let t1 = 0, t3 = 0, t5 = 0, miss = 0;
const failed = [];

CASES.forEach(c => {
  const res = search(c.q, '全部');
  const wants = c.want.map(norm);
  let rank = 0;
  for (let i = 0; i < Math.min(res.length, 10); i++) {
    const nm = norm(res[i].name);
    if (wants.some(w => nm.indexOf(w) >= 0)) { rank = i + 1; break; }
  }
  if (rank === 1) t1++;
  if (rank && rank <= 3) t3++;
  if (rank && rank <= 5) t5++;
  if (!rank) miss++;
  if (!rank || rank > 3) {
    failed.push({ q: c.q, rank, top: res.slice(0, 3).map(x => x.name), n: res.length });
  }
  if (dumpAll) {
    console.log((rank === 1 ? 'OK' : 'NG') + '\t' + c.q + '\t' + (res[0] ? res[0].name : '(空)'));
  }
});

if (dumpAll) process.exit(0);

